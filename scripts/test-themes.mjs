import { chromium } from 'playwright';
import assert from 'node:assert/strict';
import { mkdir, readFile, readdir } from 'node:fs/promises';
import { unzipSync, strFromU8 } from 'fflate';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const base = process.env.KOKI_TEST_URL || 'http://127.0.0.1:5173';
const output = path.join(root, '.cache/test-results');
await mkdir(output, { recursive: true });
const browser = await chromium.launch({ headless: true, channel: process.env.KOKI_BROWSER_CHANNEL || 'msedge' });
const errors = [];
try {
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, colorScheme: 'light', acceptDownloads: true });
  const page = await context.newPage();
  page.setDefaultTimeout(15_000);
  page.on('pageerror', error => errors.push(error.message));
  await page.goto(base);
  await page.getByRole('button', { name: 'Add your first game', exact: true }).waitFor();
  const folder = path.join(root, 'games/homebrew');
  await page.getByLabel('Import GBA games', { exact: true }).setInputFiles((await readdir(folder)).filter(file => file.endsWith('.gba')).map(file => path.join(folder, file)));
  await page.locator('.game-card').nth(4).waitFor();
  const openColors = async () => { await page.getByRole('button', { name: 'Customize colors', exact: true }).click(); await page.getByRole('heading', { name: 'Colors', exact: true }).waitFor(); await page.locator('.colors-layout').waitFor(); };
  const openSettings = async () => { await page.locator('.sidebar').getByRole('button', { name: 'Settings', exact: true }).click(); await page.locator('.settings-layout').waitFor(); assert.equal(await page.locator('.palette-picker').count(), 0, 'Settings must not contain the color palette'); assert.equal(await page.locator('.colors-layout').count(), 0, 'The separate color page must close when Settings opens'); };
  await openColors();
  const picker = page.locator('.palette-picker');
  const group = page.getByRole('radiogroup');
  const mode = name => page.locator('.colors-layout .theme-switch').getByRole('button', { name, exact: true }).click();
  const choice = value => page.waitForFunction(next => document.querySelector('.palette-grid')?.getAttribute('data-palette-choice') === next, value);
  assert.equal(await group.getByRole('radio').count(), 16);
  await group.getByRole('radio', { name: 'Ocean', exact: true }).click();
  await choice('#2563eb');
  await openSettings();
  await openColors();
  await choice('#2563eb');
  assert.equal(await group.getByRole('radio', { name: 'Ocean', exact: true }).getAttribute('aria-checked'), 'true', 'Returning through the color button must preserve the choice');
  assert.equal(await page.locator('html').getAttribute('data-theme'), 'light');
  assert.notEqual(await page.locator('html').evaluate(element => element.style.getPropertyValue('--bg')), '#f8f8f8');
  await page.locator('.colors-layout').screenshot({ path: path.join(output, 'colors-light-ocean.png') });
  await group.getByRole('radio', { name: 'Ocean', exact: true }).press('ArrowRight');
  await group.getByRole('radio', { name: 'Indigo', exact: true }).waitFor();
  assert.equal(await group.getByRole('radio', { name: 'Indigo', exact: true }).getAttribute('aria-checked'), 'true');
  const hex = page.getByRole('textbox', { name: 'Custom color hex', exact: true });
  await hex.fill('#xyzxyz');
  await page.locator('.custom-palette').getByRole('button', { name: 'Apply', exact: true }).click();
  await page.getByRole('alert').filter({ hasText: 'Enter a color' }).waitFor();
  assert.equal(await group.getAttribute('data-palette-choice'), '#4f46e5', 'Invalid custom input must not change the active theme');
  await group.getByRole('radio', { name: 'Indigo', exact: true }).click();
  assert.equal(await hex.inputValue(), '#4f46e5', 'Reselecting the active preset must reset an invalid custom draft');
  await hex.fill('#09f');
  await page.locator('.custom-palette').getByRole('button', { name: 'Apply', exact: true }).click();
  await choice('#0099ff');
  assert.equal(await hex.inputValue(), '#0099ff');
  await page.getByLabel('Custom light color', { exact: true }).evaluate(element => {
    const setter = Object.getOwnPropertyDescriptor(HTMLInputElement.prototype, 'value').set;
    setter.call(element, '#12ab34');
    element.dispatchEvent(new Event('input', { bubbles: true }));
    element.dispatchEvent(new Event('change', { bubbles: true }));
  });
  await choice('#12ab34');
  await group.getByRole('radio', { name: 'Ocean', exact: true }).click();
  await mode('Dark');
  await choice('monochrome');
  await group.getByRole('radio', { name: 'Rose', exact: true }).click();
  await choice('#e11d78');
  await page.locator('.colors-layout').screenshot({ path: path.join(output, 'colors-dark-rose.png') });
  const coloredDarkBackground = await page.locator('html').evaluate(element => element.style.getPropertyValue('--bg'));
  assert.notEqual(coloredDarkBackground, '#101010');
  await mode('Light');
  await choice('#2563eb');
  await mode('System');
  await page.emulateMedia({ colorScheme: 'dark' });
  await page.waitForFunction(() => document.documentElement.dataset.theme === 'dark');
  await choice('#e11d78');
  await page.emulateMedia({ colorScheme: 'light' });
  await page.waitForFunction(() => document.documentElement.dataset.theme === 'light');
  await choice('#2563eb');
  await page.reload();
  await openColors();
  await choice('#2563eb');
  await openSettings();
  const downloaded = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Export full backup', exact: true }).click();
  const download = await downloaded;
  const backupPath = path.join(output, 'theme-backup.koki.zip');
  await download.saveAs(backupPath);
  const manifest = JSON.parse(strFromU8(unzipSync(new Uint8Array(await readFile(backupPath)))['koki-library.json']));
  assert.equal(manifest.settings.lightColor, '#2563eb');
  assert.equal(manifest.settings.darkColor, '#e11d78');
  assert.equal(manifest.settings.theme, 'system');
  await openColors();
  await choice('#2563eb');
  await group.getByRole('radio', { name: 'Monochrome', exact: true }).click();
  await mode('Dark');
  await group.getByRole('radio', { name: 'Monochrome', exact: true }).click();
  await openSettings();
  await page.getByLabel('Restore Koki backup', { exact: true }).setInputFiles(backupPath);
  await page.getByRole('status').filter({ hasText: 'Backup restored to this device' }).waitFor();
  await openColors();
  await choice('#2563eb');
  await page.emulateMedia({ colorScheme: 'dark' });
  await choice('#e11d78');
  await page.setViewportSize({ width: 390, height: 844 });
  await picker.scrollIntoViewIfNeeded();
  while (await page.locator('.toast-close').count()) await page.locator('.toast-close').first().click();
  assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'Palette choices must fit mobile screens');
  await picker.screenshot({ path: path.join(output, 'colors-mobile.png') });
  await group.getByRole('radio', { name: 'Mint', exact: true }).click();
  await choice('#34d399');
  await page.locator('.mobile-nav').getByRole('button', { name: 'Library', exact: true }).click();
  assert.equal(await page.locator('.game-card').count(), 5);
  assert.equal(await page.locator('.game-card').first().evaluate(element => getComputedStyle(element).borderTopWidth), '0px', 'Theme customization must preserve the holder-free game layout');
  await page.screenshot({ path: path.join(output, 'colors-library-mobile.png'), fullPage: true });
  assert.deepEqual(errors, []);
  console.log(JSON.stringify({ separateColorPage: 'passed', settingsExcludePalettes: 'passed', colorButtonNavigation: 'passed', presets: 16, customHexAndPicker: 'passed', invalidInput: 'passed', keyboardSelection: 'passed', independentLightDark: 'passed', systemModeChanges: 'passed', reloadPersistence: 'passed', backupRestore: 'passed', mobileLayout: 'passed', gameLayout: 'preserved', browserErrors: errors }));
} finally { await browser.close(); }

