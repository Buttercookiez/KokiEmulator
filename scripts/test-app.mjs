import { createRequire } from 'node:module';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import assert from 'node:assert/strict';
import { makeDiagnosticRom } from './make-diagnostic-rom.mjs';

const require = createRequire(import.meta.url);
let chromium;
try { ({ chromium } = require('playwright')); }
catch { throw new Error('Install Playwright to run the app integration check.'); }
const { unzipSync, strFromU8 } = require('fflate');
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const base = process.env.KOKI_TEST_URL || 'http://127.0.0.1:5173';
const output = path.join(root, '.cache/test-results');
await mkdir(output, { recursive: true });
const diagnostic = path.join(root, '.cache/test-rom/koki-diagnostic.gba');
await mkdir(path.dirname(diagnostic), { recursive: true });
await writeFile(diagnostic, makeDiagnosticRom());
const browser = await chromium.launch({ headless: true, channel: process.env.KOKI_BROWSER_CHANNEL || 'msedge' });
const errors = [];
let page;
try {
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, colorScheme: 'light', acceptDownloads: true });
  page = await context.newPage();
  page.setDefaultTimeout(15_000);
  page.on('pageerror', error => errors.push(error.message));
  const revealPlayerControls = async () => {
    const bounds = await page.evaluate(() => ({ width: innerWidth, height: innerHeight }));
    await page.mouse.move(bounds.width / 2, 8);
    await page.locator('.player-shell[data-controls-visible="true"]').waitFor();
  };
  await page.goto(base);
  await page.getByRole('heading', { name: 'Add your games' }).waitFor();
  assert.equal(await page.locator('.game-card').count(), 0, 'A fresh library must not contain fictional games');
  await page.screenshot({ path: path.join(output, 'app-empty.png'), fullPage: true });
  await page.locator('.app-chrome .theme-switch').getByRole('button', { name: 'Dark', exact: true }).click();
  assert.equal(await page.locator('html').getAttribute('data-theme'), 'dark');
  const immediateDarkButton = await page.locator('.page-heading .button').evaluate(el => { const style = getComputedStyle(el); return { color: style.color, background: style.backgroundColor }; });
  assert.equal(immediateDarkButton.background, 'rgb(24, 24, 24)', 'Buttons must not flash white on white while changing themes');
  assert.equal(immediateDarkButton.color, 'rgb(242, 242, 242)', 'Dark-mode button text must remain readable');
  await page.reload();
  await page.getByRole('heading', { name: 'Your library' }).waitFor();
  await page.waitForFunction(() => document.documentElement.dataset.theme === 'dark');
  assert.equal(await page.locator('.page-heading h1').textContent(), 'Your library', 'The library title must be concise and have no trailing period');
  assert.equal(await page.locator('.status-dot, .local-footer, .storage-note').count(), 0, 'The library must not show decorative status bullets or extra storage copy');
  const expandedSidebarWidth = (await page.locator('.sidebar').boundingBox()).width;
  await page.getByRole('button', { name: 'Collapse sidebar', exact: true }).click();
  await page.waitForFunction(() => Boolean(document.querySelector('.sidebar-collapsed')) && document.querySelector('.sidebar').getBoundingClientRect().width < 120);
  const collapsedSidebarWidth = (await page.locator('.sidebar').boundingBox()).width;
  assert(collapsedSidebarWidth < expandedSidebarWidth / 2, 'Collapsing the sidebar must give the library more space');
  await page.locator('.sidebar').getByRole('button', { name: 'Settings', exact: true }).click();
  await page.getByRole('heading', { name: 'Settings', exact: true }).waitFor();
  await page.reload();
  await page.getByRole('button', { name: 'Expand sidebar', exact: true }).waitFor();
  assert(await page.locator('.sidebar-collapsed').count(), 'The collapsed sidebar preference must survive reload');
  await page.getByRole('button', { name: 'Expand sidebar', exact: true }).click();
  await page.waitForFunction(() => !document.querySelector('.sidebar-collapsed') && document.querySelector('.sidebar').getBoundingClientRect().width > 160);
  await page.locator('.sidebar').getByRole('button', { name: /^Library/ }).click();
  await page.locator('.app-chrome .theme-switch').getByRole('button', { name: 'Light', exact: true }).click();
  await page.getByLabel('Import GBA games', { exact: true }).setInputFiles(diagnostic);
  await page.locator('.game-card').waitFor();
  assert.equal(await page.locator('.game-card').count(), 1, 'The original diagnostic ROM should import');
  await page.locator('.game-card .card-favorite').click();
  await page.locator('.sidebar').getByRole('button', { name: 'Favorites', exact: true }).click();
  assert.equal(await page.locator('.game-card').count(), 1, 'Favorite game should appear in favorites');
  await page.getByRole('searchbox', { name: 'Search your games' }).fill('nothing matches');
  await page.getByRole('heading', { name: 'No games found' }).waitFor();
  await page.getByRole('button', { name: 'Clear search' }).click();
  await page.locator('.sidebar').getByRole('button', { name: /^Library/ }).click();
  await page.getByRole('button', { name: 'List view' }).click();
  assert.equal(await page.locator('.game-row').count(), 1, 'List view must preserve the imported game');
  await page.getByRole('button', { name: 'Grid view' }).click();
  await page.locator('.game-card .card-play').click();
  const waitColor = async color => page.waitForFunction(target => {
    const canvas = document.querySelector('.player-screen-wrap canvas');
    if (!canvas) return false;
    const pixel = canvas.getContext('2d').getImageData(120, 80, 1, 1).data;
    return target === 'green' ? pixel[1] > 200 && pixel[0] < 20 : pixel[0] > 200 && pixel[1] < 20;
  }, color, { timeout: 30_000 });
  await waitColor('green');
  await page.keyboard.down('KeyX');
  await waitColor('red');
  await page.keyboard.up('KeyX');
  await waitColor('green');
  await revealPlayerControls();
  await page.locator('.player-toolbar').getByRole('button', { name: /^Save(?: F5)?$/ }).click();
  await page.getByRole('status').filter({ hasText: 'Checkpoint saved on this device' }).waitFor();
  await revealPlayerControls();
  await page.getByRole('button', { name: 'Save and return to library' }).click();
  await page.locator('.player-shell').waitFor({ state: 'detached' });
  const resume = page.getByRole('button', { name: 'Resume game', exact: true });
  await resume.waitFor();
  await resume.hover();
  await resume.evaluate(element => { getComputedStyle(element).backgroundColor; return Promise.all(element.getAnimations().map(animation => animation.finished.catch(() => {}))); });
  const resumeHoverContrast = await resume.evaluate(element => {
    const style = getComputedStyle(element);
    const rgb = value => value.match(/[\d.]+/g).slice(0, 3).map(Number);
    const luminance = color => rgb(color).map(value => { const channel = value / 255; return channel <= .04045 ? channel / 12.92 : ((channel + .055) / 1.055) ** 2.4; }).reduce((value, channel, index) => value + channel * [.2126, .7152, .0722][index], 0);
    const light = luminance(style.backgroundColor), dark = luminance(style.color);
    return { foreground: style.color, background: style.backgroundColor, contrast: (Math.max(light, dark) + .05) / (Math.min(light, dark) + .05) };
  });
  assert(resumeHoverContrast.contrast >= 4.5, 'Resume game must stay readable when hovered');
  assert.equal(await page.locator('.status-dot').count(), 0, 'Continue playing must not reintroduce a decorative bullet');
  await page.reload();
  await page.getByRole('button', { name: 'Resume game', exact: true }).waitFor();
  await page.getByRole('button', { name: 'Resume game', exact: true }).click();
  await waitColor('green');
  await revealPlayerControls();
  await page.getByRole('button', { name: 'Save and return to library' }).click();
  await page.locator('.player-shell').waitFor({ state: 'detached' });
  await page.locator('.game-card .game-cover-button').click();
  await page.getByRole('dialog', { name: 'Game details' }).waitFor();
  await page.getByRole('button', { name: 'Play from Quick save', exact: true }).click();
  await waitColor('green');
  await revealPlayerControls();
  await page.getByRole('button', { name: 'Save and return to library' }).click();
  await page.locator('.player-shell').waitFor({ state: 'detached' });
  await page.locator('.sidebar').getByRole('button', { name: 'Settings', exact: true }).click();
  const chromeBefore = await page.locator('.app-chrome').boundingBox();
  assert.equal(await page.locator('.app-chrome').evaluate(element => getComputedStyle(element).position), 'sticky', 'The top bar must stay attached while scrolling');
  await page.evaluate(() => window.scrollTo(0, 600));
  await page.waitForFunction(() => scrollY > 100);
  const chromeAfter = await page.locator('.app-chrome').boundingBox();
  assert(Math.abs(chromeAfter.y - chromeBefore.y) <= 1, 'The top bar must stay in the same screen position after scrolling');
  await page.evaluate(() => window.scrollTo(0, 0));
  const downloaded = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Export full backup' }).click();
  const download = await downloaded;
  const backupPath = path.join(output, 'ui-backup.koki.zip');
  await download.saveAs(backupPath);
  const archive = unzipSync(new Uint8Array(await readFile(backupPath)));
  const manifest = JSON.parse(strFromU8(archive['koki-library.json']));
  assert.equal(manifest.games.length, 1, 'Export must contain the imported game');
  assert(manifest.snapshots.some(snapshot => snapshot.kind === 'manual'), 'Export must contain the quicksave');
  const battery = archive[`data/saves/${manifest.games[0].id}.sav`];
  assert(battery?.[0] === 0x4b, 'Diagnostic battery SRAM should survive save and reload');
  await page.locator('.sidebar').getByRole('button', { name: /^Library/ }).click();
  await page.waitForFunction(() => !document.querySelector('.page-heading .button')?.disabled);
  while (await page.locator('.toast-close').count()) await page.locator('.toast-close').first().click();
  await page.screenshot({ path: path.join(output, 'app-desktop.png'), fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.locator('.theme-cycle').click();
  await page.waitForFunction(() => document.documentElement.dataset.theme === 'dark');
  assert.equal(await page.locator('.mobile-nav').isVisible(), true, 'Android layout should expose bottom navigation');
  assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'Android library must not overflow horizontally');
  await page.screenshot({ path: path.join(output, 'app-android.png') });
  await page.locator('.game-card .card-play').click();
  await waitColor('green');
  await revealPlayerControls();
  const aButton = page.getByRole('button', { name: 'A button', exact: true });
  await aButton.hover();
  await page.mouse.down();
  await waitColor('red');
  await page.mouse.up();
  await waitColor('green');
  await revealPlayerControls();
  await page.getByRole('button', { name: 'Save and return to library' }).click();
  await page.locator('.player-shell').waitFor({ state: 'detached' });
  assert.deepEqual(errors, [], 'The UI must not produce uncaught browser exceptions');
  const report = { app: 'passed', base, isolatedContext: true, emptyLibrary: 'passed', themePersistence: 'passed', sidebarCollapseAndPersistence: 'passed', stickyTopBar: 'passed', minimalistCopy: 'passed', resumeHoverContrast, immediateThemeContrast: immediateDarkButton, import: 'passed', favoritesSearchAndViews: 'passed', gameInput: 'green→red→green', quicksave: 'passed', localResume: 'passed', snapshotRestore: 'passed', batterySave: '0x4b', backup: { gameCount: manifest.games.length, snapshots: manifest.snapshots.length }, responsiveAndroid: 'passed', browserErrors: errors };
  await writeFile(path.join(output, 'app-test-report.json'), JSON.stringify(report, null, 2));
  console.log(JSON.stringify(report));
} catch (error) {
  if (page && !page.isClosed()) await page.screenshot({ path: path.join(output, 'app-failure.png'), fullPage: true }).catch(() => {});
  throw error;
} finally {
  await browser.close();
}
