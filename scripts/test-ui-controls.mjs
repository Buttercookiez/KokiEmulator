import { chromium } from 'playwright';
import assert from 'node:assert/strict';
import { mkdir, readdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { makeDiagnosticRom } from './make-diagnostic-rom.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const output = path.join(root, '.cache/test-results');
await mkdir(output, { recursive: true });
const base = process.env.KOKI_TEST_URL || 'http://127.0.0.1:5173';
const browser = await chromium.launch({ headless: true, channel: process.env.KOKI_BROWSER_CHANNEL || 'msedge' });
const errors = [];
try {
  const context = await browser.newContext({ viewport: { width: 1326, height: 940 }, colorScheme: 'dark' });
  const page = await context.newPage();
  page.setDefaultTimeout(15_000);
  page.on('pageerror', error => errors.push(error.message));
  await page.goto(base);
  await page.getByRole('button', { name: 'Add your first game', exact: true }).waitFor();
  const folder = path.join(root, 'games/homebrew');
  const roms = (await readdir(folder)).filter(name => name.endsWith('.gba')).map(name => path.join(folder, name));
  assert.equal(roms.length, 5);
  await page.getByLabel('Import GBA games', { exact: true }).setInputFiles(roms);
  await page.locator('.game-card').nth(4).waitFor();
  await page.waitForFunction(() => [...document.querySelectorAll('.game-card .cover-art')].length === 5 && [...document.querySelectorAll('.game-card .cover-art')].every(image => image.complete && image.naturalWidth > 0));
  await page.screenshot({ path: path.join(output, 'updated-library-dark.png'), fullPage: true });
  const sort = page.getByRole('combobox', { name: 'Sort games', exact: true });
  await sort.click();
  const popup = page.getByRole('listbox', { name: 'Sort games', exact: true });
  await popup.waitFor();
  assert.equal(await page.locator('select').count(), 0, 'Native dropdowns should use the shared styled component');
  await page.screenshot({ path: path.join(output, 'updated-dropdown-dark.png'), fullPage: true });
  await sort.press('End');
  const active = await sort.getAttribute('aria-activedescendant');
  assert(active && await page.locator('[id="' + active + '"]').textContent() === 'Recently added');
  await sort.press('Escape');
  assert.equal(await sort.textContent(), 'Recently played', 'Escape must preserve the selected value');
  await sort.press('t');
  await sort.press('Enter');
  assert.equal(await sort.textContent(), 'Title A–Z', 'Typeahead and Enter should select an option');
  await sort.click();
  await page.getByRole('heading', { name: 'Your library', exact: true }).click();
  await popup.waitFor({ state: 'detached' });
  const search = page.getByRole('searchbox', { name: 'Search your games', exact: true });
  await search.click();
  const focus = await search.evaluate(element => ({ outline: getComputedStyle(element).outlineStyle, shadow: getComputedStyle(element).boxShadow }));
  assert.deepEqual(focus, { outline: 'none', shadow: 'none' }, 'Search must not show a second box inside its wrapper');
  assert.equal(await page.locator('.search-field kbd').count(), 0, 'Search shortcut should not have a boxed keycap');
  await search.fill('Skyland');
  assert.equal(await page.locator('.game-card').count(), 1);
  await search.fill('');
  await page.locator('.sidebar').getByRole('button', { name: 'Settings', exact: true }).click();
  for (const [name, option] of [['Screen filter', 'Smooth'], ['Default playback speed', '2×'], ['Rewind history', '20 seconds']]) {
    const trigger = page.getByRole('combobox', { name, exact: true });
    await trigger.click();
    await page.getByRole('option', { name: option, exact: true }).click();
    assert.equal(await trigger.textContent(), option);
    await page.getByRole('listbox', { name, exact: true }).waitFor({ state: 'detached' });
  }
  await page.locator('.app-chrome .theme-switch').getByRole('button', { name: 'Light', exact: true }).click();
  await page.getByRole('combobox', { name: 'Screen filter', exact: true }).click();
  assert.equal(await page.getByRole('listbox').evaluate(element => getComputedStyle(element).backgroundColor), 'rgb(255, 255, 255)');
  await page.screenshot({ path: path.join(output, 'updated-dropdown-light.png'), fullPage: true });
  await page.keyboard.press('Escape');
  await page.setViewportSize({ width: 390, height: 844 });
  await page.getByRole('combobox', { name: 'Rewind history', exact: true }).click();
  const bounds = await page.getByRole('listbox').boundingBox();
  assert(bounds && bounds.x >= 0 && bounds.y >= 0 && bounds.x + bounds.width <= 390 && bounds.y + bounds.height <= 844, 'Mobile menu must fit on screen');
  await page.screenshot({ path: path.join(output, 'updated-dropdown-mobile.png'), fullPage: true });
  await page.keyboard.press('Escape');
  await page.locator('.mobile-nav').getByRole('button', { name: 'Library', exact: true }).click();
  assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'Mobile library must not overflow horizontally');
  await page.screenshot({ path: path.join(output, 'updated-library-mobile.png'), fullPage: true });
  await page.setViewportSize({ width: 1326, height: 940 });
  await page.getByLabel('Import GBA games', { exact: true }).setInputFiles({ name: 'Koki diagnostic.gba', mimeType: 'application/octet-stream', buffer: Buffer.from(makeDiagnosticRom()) });
  await page.getByRole('button', { name: 'Play Koki diagnostic', exact: true }).click();
  await page.waitForFunction(() => document.querySelector('.player-screen-wrap canvas')?.getContext('2d').getImageData(120, 80, 1, 1).data[1] > 200);
  await page.waitForFunction(() => Boolean(document.fullscreenElement));
  await page.mouse.move((await page.evaluate(() => innerWidth)) / 2, 8);
  await page.locator('.player-shell[data-controls-visible="true"]').waitFor();
  await page.getByRole('combobox', { name: 'Playback speed', exact: true }).click();
  assert(await page.getByRole('listbox', { name: 'Playback speed', exact: true }).evaluate(element => document.fullscreenElement?.contains(element)), 'Player dropdown must stay inside fullscreen');
  await page.getByRole('option', { name: '1×', exact: true }).click();
  await page.mouse.move((await page.evaluate(() => innerWidth)) / 2, 8);
  await page.getByRole('button', { name: 'Toggle fullscreen', exact: true }).click();
  await page.waitForFunction(() => !document.fullscreenElement);
  await page.mouse.move((await page.evaluate(() => innerWidth)) / 2, 8);
  await page.getByRole('button', { name: 'Save and return to library', exact: true }).click();
  await page.locator('.player-shell').waitFor({ state: 'detached' });
  assert.deepEqual(errors, []);
  console.log(JSON.stringify({ artwork: '5 bundled covers', dropdowns: 'sort, filter, default speed, rewind, player speed', keyboardNavigation: 'passed', searchFocus: 'passed', mobileLayout: 'passed', fullscreenPopup: 'passed', browserErrors: errors }));
} finally { await browser.close(); }

