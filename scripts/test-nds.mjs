import { chromium } from 'playwright';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
const out = '.cache/nds-tests';
await fs.mkdir(out, { recursive: true });
const browser = await chromium.launch({ headless: true, channel: 'msedge' });
const errors = [];
const results = [];
try {
    const context = await browser.newContext({ viewport: { width: 1280, height: 900 }, colorScheme: 'dark' }), page = await context.newPage();
    page.setDefaultTimeout(20000);
    page.on('pageerror', e => errors.push(e.message));
    await page.goto('http://127.0.0.1:5175');
    await page.getByLabel('Import NDS games', { exact: true }).setInputFiles(out + '/koki-ds-diagnostic.nds');
    await page.getByRole('button', { name: 'Play koki-ds-diagnostic', exact: true }).click();
    await page.waitForFunction(() => { const c = document.querySelector('canvas'); return c && c.getContext('2d').getImageData(120, 96, 1, 1).data[2] > 200; });
    await page.keyboard.down('x');
    await page.waitForFunction(() => document.querySelector('canvas').getContext('2d').getImageData(120, 96, 1, 1).data[0] > 200);
    await page.keyboard.up('x');
    await page.waitForFunction(() => document.querySelector('canvas').getContext('2d').getImageData(120, 96, 1, 1).data[2] > 200);
    results.push('real dual-screen ARM9/ARM7 emulation and keyboard A');
    await page.mouse.move(600, 40);
    await page.getByRole('combobox', { name: 'DS screen layout' }).click();
    await page.getByRole('option', { name: 'Side by side', exact: true }).click();
    await page.waitForFunction(() => document.querySelector('canvas').width === 512);
    await page.getByRole('button', { name: 'Swap screens', exact: true }).click();
    const colors = await page.locator('canvas').evaluate(c => { const x = c.getContext('2d'); return { left: [...x.getImageData(120, 96, 1, 1).data], right: [...x.getImageData(376, 96, 1, 1).data] }; });
    assert(colors.left[1] > 200 && colors.right[2] > 200);
    await page.screenshot({ path: out + '/desktop-dual.png' });
    results.push('side-by-side layout and swapped screens');
    await page.keyboard.press('F5');
    await page.getByText('Checkpoint saved on this device', { exact: true }).waitFor();
    await page.locator('canvas').focus();
    await page.keyboard.press('Space');
    await page.reload();
    await page.getByRole('button', { name: 'Resume game', exact: true }).click();
    await page.waitForFunction(() => { const c = document.querySelector('canvas'); return c?.width === 512 && c.getContext('2d').getImageData(120, 96, 1, 1).data[1] > 200; });
    console.log('Reload settings', await page.evaluate(async () => { const l = await import('/src/lib/library.ts'); const s = await l.getSettings(); return { dsLayout: s.dsLayout, dsSwap: s.dsSwap }; }));
    results.push('large DS checkpoint and reload auto-resume');
    await page.mouse.move(600, 40);
    await page.getByRole('button', { name: 'Save and return to library', exact: true }).click();
    await page.getByRole('heading', { name: 'Your library', exact: true }).waitFor();
    const zip = await page.evaluate(async () => { const lib = await import('/src/lib/library.ts'); const blob = await lib.exportLibrary(); return [...new Uint8Array(await blob.arrayBuffer())]; });
    await fs.writeFile(out + '/nds-backup.koki.zip', Buffer.from(zip));
    await context.close();
    const mobile = await browser.newContext({ viewport: { width: 390, height: 844 }, hasTouch: true, isMobile: true, colorScheme: 'dark' }), p = await mobile.newPage();
    p.on('pageerror', e => errors.push(e.message));
    await p.goto('http://127.0.0.1:5175');
    await p.getByRole('button', { name: 'Add your first game', exact: true }).waitFor();
    await p.evaluate(async (data) => { const lib = await import('/src/lib/library.ts'); await lib.importLibrary(new File([new Uint8Array(data)], 'library.koki.zip')); }, zip);
    await p.reload();
    await p.getByRole('button', { name: 'Resume game', exact: true }).click();
    await p.getByRole('button', { name: 'X', exact: true }).waitFor();
    const xSize = await p.getByRole('button', { name: 'X', exact: true }).boundingBox();
    assert(xSize.width >= 57 && xSize.height >= 57, 'X must have a full-size usable touch target');
    const rSize = await p.getByRole('button', { name: 'R shoulder', exact: true }).boundingBox();
    assert(xSize.y >= rSize.y + rSize.height + 4, 'Default X and R touch areas must not overlap');
    await p.getByRole('button', { name: 'Open game menu', exact: true }).click();
    await p.getByRole('button', { name: 'Edit controls', exact: true }).click();
    await p.getByRole('combobox', { name: 'Control to resize' }).click();
    await p.getByRole('option', { name: 'X', exact: true }).click();
    await p.getByRole('slider', { name: 'Control size', exact: true }).fill('1.4');
    await p.getByRole('button', { name: 'Done', exact: true }).click();
    const resizedX = await p.getByRole('button', { name: 'X', exact: true }).boundingBox();
    assert(resizedX.width >= 80 && resizedX.height >= 80, 'Resizing must change the actual touch button');
    await p.getByRole('button', { name: 'Open game menu', exact: true }).click();
    await p.getByRole('button', { name: 'Save and return to library', exact: true }).click();
    await p.getByRole('heading', { name: 'Your library', exact: true }).waitFor();
    await p.screenshot({ path: out + '/mobile-library.png' });
    results.push('native-format backup restore, mobile X/Y controls and resize profile');
    const saved = await p.evaluate(async () => { const lib = await import('/src/lib/library.ts'); return { games: await lib.getGames(), saves: await lib.getSnapshots() }; });
    assert.equal(saved.games[0].profile.touchLayouts.portrait.x.scale, 1.4);
    assert(saved.saves.length > 0);
    assert.equal(saved.games.length, 1);
    await p.getByRole('button', { name: 'Settings', exact: true }).click();
    await p.getByRole('button', { name: 'Change X key, currently I', exact: true }).click();
    await p.keyboard.press('o');
    await p.reload();
    await p.getByRole('button', { name: 'Settings', exact: true }).click();
    await p.getByRole('button', { name: 'Change X key, currently O', exact: true }).waitFor();
    results.push('DS X/Y keyboard remapping survives reload');
    assert.deepEqual(errors, []);
    await fs.writeFile(out + '/report.json', JSON.stringify({ status: 'passed', core: 'melonDS/Pilas pinned', results, errors, physicalAndroid: 'not tested', commercialGames: 'not tested' }, null, 2));
    console.log(JSON.stringify({ status: 'passed', results }));
    await mobile.close();
}
catch (e) {
    console.error(e);
    throw e;
}
finally {
    await browser.close();
}
