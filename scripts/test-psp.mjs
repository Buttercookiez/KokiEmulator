import { _electron as electron } from 'playwright';
import fs from 'node:fs/promises';
import path from 'node:path';
import assert from 'node:assert/strict';
const root=process.cwd();
const demo=process.env.KOKI_PSP_DEMO;
if(!demo)throw Error('Set KOKI_PSP_DEMO to PPSSPP cube.elf.');
const profile=path.join(root,'.cache','psp-tests','windows-'+Date.now());
await fs.mkdir(profile,{recursive:true});
const second=path.join(profile,'Second demo.elf');
await fs.copyFile(demo,second);
const app=await electron.launch({args:['.'],env:{...process.env,KOKI_SYSTEM:'psp',KOKI_TEST_MODE:'1',KOKI_TEST_DATA_DIR:profile}});
try {
  const page=await app.firstWindow();
  page.setDefaultTimeout(30000);
  const errors=[];
  page.on('pageerror',error=>errors.push(error.message));
  await app.evaluate(({BrowserWindow})=>BrowserWindow.getAllWindows()[0].showInactive());
  await page.getByRole('heading',{name:'Your library',exact:true}).waitFor();
  await app.evaluate(({dialog},files)=>{dialog.showOpenDialog=async()=>({canceled:false,filePaths:files});},[demo,second]);
  await page.getByRole('button',{name:'Add games',exact:true}).click();
  await page.getByRole('button',{name:'Play Second demo',exact:true}).waitFor();
  let games=await page.evaluate(()=>window.kokiPsp.games());
  assert.equal(games.length,2);
  await page.getByRole('button',{name:'Play '+games[0].title,exact:true}).click();
  await page.waitForFunction(()=>{const canvas=document.querySelector('canvas');if(!canvas)return false;const pixels=canvas.getContext('2d').getImageData(0,0,480,272).data;return pixels.some((value,index)=>index%4!==3&&value>60);});
  await page.waitForTimeout(1100);
  await page.getByRole('button',{name:'Save',exact:true}).click();
  await page.getByRole('status').filter({hasText:'Checkpoint saved'}).waitFor();
  let states=await page.evaluate(()=>window.kokiPsp.checkpoints());
  assert.equal(states.length,1);
  await page.getByRole('button',{name:'Return to library',exact:true}).click();
  await page.getByRole('heading',{name:'Your library',exact:true}).waitFor();
  games=await page.evaluate(()=>window.kokiPsp.games());
  assert.ok(games[0].screenshot?.startsWith('data:image/png;base64,'));
  await page.getByRole('button',{name:'Saves',exact:true}).first().click();
  await page.getByText('1 checkpoints',{exact:true}).click();
  await page.getByRole('button',{name:'Load',exact:true}).click();
  await page.waitForFunction(()=>!!document.querySelector('canvas'));
  await page.getByRole('button',{name:'Return to library',exact:true}).click();
  await page.getByRole('heading',{name:'Your library',exact:true}).waitFor();
  await page.getByRole('button',{name:'Colors',exact:true}).click();
  await page.getByRole('button',{name:'Ocean',exact:true}).click();
  assert.ok(await page.evaluate(()=>JSON.parse(localStorage.getItem('koki-psp-settings')).lightColor==='#2563eb'||JSON.parse(localStorage.getItem('koki-psp-settings')).darkColor==='#2563eb'));
  await app.evaluate(({BrowserWindow})=>{const window=BrowserWindow.getAllWindows()[0];window.setMinimumSize(320,320);window.setContentSize(412,915);});
  await page.addInitScript(()=>{const original=window.matchMedia.bind(window);window.matchMedia=query=>query==='(pointer: coarse)'?Object.defineProperty(original(query),'matches',{value:true}):original(query);});
  await page.reload();
  await page.getByRole('heading',{name:'Your library',exact:true}).waitFor();
  await page.getByRole('button',{name:'Play Second demo',exact:true}).click();
  await page.getByRole('button',{name:'Player menu',exact:true}).click();
  await page.getByRole('button',{name:'Edit controls',exact:true}).click();
  await page.getByRole('region',{name:'Edit PSP controls'}).waitFor();
  const cross=page.locator('[data-psp-control="cross"]');
  const box=await cross.boundingBox();
  await page.mouse.move(box.x+box.width/2,box.y+box.height/2);
  await page.mouse.down();
  await page.mouse.move(box.x+box.width/2-25,box.y+box.height/2-20,{steps:5});
  await page.mouse.up();
  await page.getByRole('button',{name:'Save for all games',exact:true}).click();
  const layout=await page.evaluate(()=>JSON.parse(localStorage.getItem('koki-psp-settings')).layout.portrait);
  assert.ok(layout&&layout.cross.x<78);
  await page.getByRole('button',{name:'Return to library',exact:true}).click();
  await page.getByRole('heading',{name:'Your library',exact:true}).waitFor();
  await page.getByRole('button',{name:'Play '+games[0].title,exact:true}).click();
  const position=await page.locator('[data-psp-control="cross"]').evaluate(node=>node.style.left);
  assert.ok(Math.abs(parseFloat(position)-layout.cross.x)<.001);
  await page.getByRole('button',{name:'Return to library',exact:true}).click();
  await page.getByRole('heading',{name:'Your library',exact:true}).waitFor();
  const shots=path.join(root,'.cache/psp-tests');await fs.mkdir(shots,{recursive:true});
  await page.waitForTimeout(700);
  await page.screenshot({path:path.join(shots,'mobile-library.png')});
  await app.evaluate(({BrowserWindow})=>BrowserWindow.getAllWindows()[0].setContentSize(1280,840));
  await page.waitForTimeout(400);
  await page.screenshot({path:path.join(shots,'windows-library.png')});
  assert.deepEqual(errors,[]);
  console.log('Passed real PPSSPP gameplay, checkpoint save/restore, screenshots, themes, mobile navigation and shared controls across games.');
} catch (error) {
  const page=await app.firstWindow();
  console.log('PSP test page:', await page.locator('body').innerText());
  await page.screenshot({path:path.join(root,'.cache/psp-test-failure.png')});
  throw error;
} finally { await app.close(); }
